-- ── FUNCTION: register_fixed_asset ───────────────────────────────────────────
-- Registers a new fixed asset and optionally posts the acquisition journal entry.
-- Transitions asset to 'active' immediately.
--
-- Acquisition journal (if p_period_id IS NOT NULL):
--   DR asset_class.asset_account (acquisition_cost)    — e.g. 1250 Inventarier
--   CR p_credit_account (default '2440')               — e.g. 2440 Leverantörsskulder
-- Voucher series 'D'.

CREATE OR REPLACE FUNCTION public.register_fixed_asset(
  p_org_id               uuid,
  p_period_id            uuid,
  p_asset_class_id       uuid,
  p_asset_code           text,
  p_asset_name           text,
  p_acquisition_date     date,
  p_acquisition_cost     numeric(14,2),
  p_residual_value       numeric(14,2)            DEFAULT 0,
  p_useful_life_months   int                      DEFAULT 60,
  p_depreciation_method  public.depreciation_method DEFAULT 'straight_line',
  p_credit_account       text                     DEFAULT '2440',
  p_description          text                     DEFAULT NULL,
  p_notes                text                     DEFAULT NULL,
  p_actor_id             uuid                     DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_asset_id  uuid;
  v_class     public.fixed_asset_classes%ROWTYPE;
  v_entry_id  uuid;
  v_lines     jsonb;
BEGIN
  SELECT * INTO v_class FROM public.fixed_asset_classes WHERE id = p_asset_class_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ASSET_CLASS_NOT_FOUND: class % does not exist', p_asset_class_id
      USING ERRCODE = 'P0002';
  END IF;

  IF p_acquisition_cost <= 0 THEN
    RAISE EXCEPTION 'ASSET_INVALID_COST: acquisition_cost must be positive'
      USING ERRCODE = 'P0001';
  END IF;
  IF p_residual_value >= p_acquisition_cost THEN
    RAISE EXCEPTION 'ASSET_RESIDUAL_GEQ_COST: residual_value (%) must be less than acquisition_cost (%)',
      p_residual_value, p_acquisition_cost
      USING ERRCODE = 'P0001';
  END IF;

  -- Insert asset record directly as 'active'
  INSERT INTO public.fixed_assets
    (organization_id, asset_class_id, financial_period_id, asset_code, asset_name,
     description, acquisition_date, acquisition_cost, residual_value, useful_life_months,
     depreciation_method, status, net_book_value, accumulated_depreciation, periods_posted,
     notes, created_by)
  VALUES
    (p_org_id, p_asset_class_id, p_period_id, p_asset_code, p_asset_name,
     p_description, p_acquisition_date, p_acquisition_cost, p_residual_value, p_useful_life_months,
     p_depreciation_method, 'active', p_acquisition_cost, 0, 0,
     p_notes, p_actor_id)
  RETURNING id INTO v_asset_id;

  -- Post acquisition journal if period provided
  IF p_period_id IS NOT NULL THEN
    v_lines := jsonb_build_array(
      jsonb_build_object(
        'account_code',  v_class.asset_account,
        'debit_amount',  p_acquisition_cost,
        'credit_amount', 0,
        'description',   'Anskaffning: ' || p_asset_name
      ),
      jsonb_build_object(
        'account_code',  p_credit_account,
        'debit_amount',  0,
        'credit_amount', p_acquisition_cost,
        'description',   'Anskaffning: ' || p_asset_name
      )
    );

    v_entry_id := public.post_journal_entry(
      p_org_id,
      p_period_id,
      'standard'::public.journal_entry_type,
      p_acquisition_date,
      'Anskaffning anläggningstillgång: ' || p_asset_name,
      v_lines,
      'FixedAsset.Acquired',
      'fixed_asset',
      v_asset_id,
      'D',
      NULL, NULL,
      p_actor_id
    );

    UPDATE public.fixed_assets
    SET acquisition_entry_id = v_entry_id
    WHERE id = v_asset_id;
  END IF;

  RETURN v_asset_id;
END;
$$;

COMMENT ON FUNCTION public.register_fixed_asset(uuid,uuid,uuid,text,text,date,numeric,numeric,int,public.depreciation_method,text,text,text,uuid) IS
  'Registers a new fixed asset, immediately activates it, and optionally posts the '
  'acquisition journal (DR asset_account / CR p_credit_account, default 2440). '
  'Returns the asset id.';

GRANT EXECUTE ON FUNCTION public.register_fixed_asset(uuid,uuid,uuid,text,text,date,numeric,numeric,int,public.depreciation_method,text,text,text,uuid) TO service_role;

-- ── FUNCTION: generate_depreciation_schedule ────────────────────────────────
-- Generates the full predetermined depreciation schedule for an asset.
-- Idempotent: deletes existing unposted lines before regenerating.
-- Starts from (periods_posted + 1) at current net_book_value.
-- Returns count of schedule lines generated.

CREATE OR REPLACE FUNCTION public.generate_depreciation_schedule(
  p_asset_id uuid,
  p_actor_id uuid DEFAULT NULL
)
RETURNS int
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_asset          public.fixed_assets%ROWTYPE;
  v_period_amount  numeric(14,2);
  v_opening_nbv    numeric(14,2);
  v_closing_nbv    numeric(14,2);
  v_schedule_date  date;
  v_start_period   int;
  v_count          int := 0;
  i                int;
BEGIN
  SELECT * INTO v_asset FROM public.fixed_assets WHERE id = p_asset_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ASSET_NOT_FOUND: asset % does not exist', p_asset_id
      USING ERRCODE = 'P0002';
  END IF;

  IF v_asset.status = 'disposed' THEN
    RAISE EXCEPTION 'ASSET_DISPOSED: cannot generate schedule for a disposed asset'
      USING ERRCODE = 'P0001';
  END IF;

  IF v_asset.depreciation_method = 'none' THEN
    RETURN 0;
  END IF;

  -- Delete unposted lines (allows idempotent regeneration and post-impairment regeneration)
  DELETE FROM public.depreciation_schedules
  WHERE  asset_id  = p_asset_id
    AND  is_posted = false;

  v_start_period  := v_asset.periods_posted + 1;
  v_opening_nbv   := v_asset.net_book_value;

  -- First unposted schedule_date: month after acquisition + already-posted months
  v_schedule_date := (
    date_trunc('month', v_asset.acquisition_date + interval '1 month')
    + (v_asset.periods_posted * interval '1 month')
  )::date;

  -- Straight-line: constant amount per period
  IF v_asset.depreciation_method = 'straight_line' THEN
    v_period_amount := ROUND(
      (v_asset.acquisition_cost - v_asset.residual_value) / v_asset.useful_life_months, 2
    );
  END IF;

  i := v_start_period;

  WHILE i <= v_asset.useful_life_months AND v_opening_nbv > v_asset.residual_value LOOP
    -- Declining balance: recalculate each period on current NBV
    IF v_asset.depreciation_method = 'declining_balance' THEN
      v_period_amount := ROUND(
        v_opening_nbv * 2.0 / v_asset.useful_life_months, 2
      );
    END IF;

    -- Clamp: do not depreciate below residual value
    v_period_amount := LEAST(v_period_amount, v_opening_nbv - v_asset.residual_value);

    -- Final period: absorb accumulated rounding to reach exactly residual_value
    IF i = v_asset.useful_life_months OR
       (v_opening_nbv - v_period_amount) < (v_asset.residual_value + 0.01) THEN
      v_period_amount := v_opening_nbv - v_asset.residual_value;
    END IF;

    v_closing_nbv := v_opening_nbv - v_period_amount;

    INSERT INTO public.depreciation_schedules
      (organization_id, asset_id, period_number, schedule_date,
       depreciation_amount, opening_nbv, closing_nbv)
    VALUES
      (v_asset.organization_id, p_asset_id, i, v_schedule_date,
       v_period_amount, v_opening_nbv, v_closing_nbv);

    v_opening_nbv   := v_closing_nbv;
    v_schedule_date := (v_schedule_date + interval '1 month')::date;
    i               := i + 1;
    v_count         := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$;

COMMENT ON FUNCTION public.generate_depreciation_schedule(uuid, uuid) IS
  'Generates the full predetermined depreciation schedule for an asset. '
  'Deletes unposted lines first (idempotent). '
  'Supports straight_line and declining_balance methods. '
  'Final-period rounding absorbed to reach exactly residual_value. '
  'Returns count of schedule lines created.';

GRANT EXECUTE ON FUNCTION public.generate_depreciation_schedule(uuid, uuid) TO service_role;

-- ── FUNCTION: post_depreciation_period ───────────────────────────────────────
-- Posts the next pending depreciation period for an asset.
-- Uses the lowest period_number unposted line from depreciation_schedules.
-- Returns the journal entry id.

CREATE OR REPLACE FUNCTION public.post_depreciation_period(
  p_asset_id  uuid,
  p_period_id uuid,
  p_actor_id  uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_asset     public.fixed_assets%ROWTYPE;
  v_class     public.fixed_asset_classes%ROWTYPE;
  v_schedule  public.depreciation_schedules%ROWTYPE;
  v_entry_id  uuid;
  v_lines     jsonb;
BEGIN
  SELECT * INTO v_asset FROM public.fixed_assets WHERE id = p_asset_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ASSET_NOT_FOUND: asset % does not exist', p_asset_id
      USING ERRCODE = 'P0002';
  END IF;

  IF v_asset.status NOT IN ('active', 'impaired') THEN
    RAISE EXCEPTION
      'ASSET_NOT_DEPRECIABLE: asset status is %. Only active or impaired assets can be depreciated.',
      v_asset.status
      USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_class FROM public.fixed_asset_classes WHERE id = v_asset.asset_class_id;

  SELECT * INTO v_schedule
  FROM   public.depreciation_schedules
  WHERE  asset_id  = p_asset_id
    AND  is_posted = false
  ORDER  BY period_number ASC
  LIMIT  1;

  IF NOT FOUND THEN
    RAISE EXCEPTION
      'NO_DEPRECIATION_DUE: no unposted depreciation schedule line for asset %', p_asset_id
      USING ERRCODE = 'P0001';
  END IF;

  -- DR depreciation_exp_account / CR accumulated_depr_account
  v_lines := jsonb_build_array(
    jsonb_build_object(
      'account_code',  v_class.depreciation_exp_account,
      'debit_amount',  v_schedule.depreciation_amount,
      'credit_amount', 0,
      'description',
        'Avskrivning: ' || v_asset.asset_name
        || ' (' || v_schedule.period_number || '/' || v_asset.useful_life_months || ')'
    ),
    jsonb_build_object(
      'account_code',  v_class.accumulated_depr_account,
      'debit_amount',  0,
      'credit_amount', v_schedule.depreciation_amount,
      'description',   v_asset.asset_name || ' ackumulerade avskrivningar'
    )
  );

  v_entry_id := public.post_journal_entry(
    v_asset.organization_id,
    p_period_id,
    'standard'::public.journal_entry_type,
    v_schedule.schedule_date,
    'Avskrivning ' || v_asset.asset_name
      || ' period ' || v_schedule.period_number || '/' || v_asset.useful_life_months,
    v_lines,
    'FixedAsset.Depreciated',
    'fixed_asset',
    p_asset_id,
    'D',
    NULL, NULL,
    p_actor_id
  );

  -- Mark line posted
  UPDATE public.depreciation_schedules
  SET is_posted = true, posted_at = now(), journal_entry_id = v_entry_id
  WHERE id = v_schedule.id;

  -- Update asset running totals
  UPDATE public.fixed_assets
  SET accumulated_depreciation = accumulated_depreciation + v_schedule.depreciation_amount,
      net_book_value            = net_book_value - v_schedule.depreciation_amount,
      periods_posted            = periods_posted + 1,
      last_depreciation_date    = v_schedule.schedule_date,
      status = CASE
        WHEN (net_book_value - v_schedule.depreciation_amount) <= residual_value + 0.01
        THEN 'fully_depreciated'::public.fixed_asset_status
        ELSE status
      END,
      fully_depreciated_at = CASE
        WHEN (net_book_value - v_schedule.depreciation_amount) <= residual_value + 0.01
          AND fully_depreciated_at IS NULL
        THEN v_schedule.schedule_date
        ELSE fully_depreciated_at
      END,
      updated_by = p_actor_id,
      updated_at = now()
  WHERE id = p_asset_id;

  RETURN v_entry_id;
END;
$$;

COMMENT ON FUNCTION public.post_depreciation_period(uuid, uuid, uuid) IS
  'Posts the next pending depreciation period for an asset. '
  'Selects the lowest unposted period_number from depreciation_schedules. '
  'Journal: DR depreciation_exp_account / CR accumulated_depr_account. '
  'Updates asset.net_book_value, accumulated_depreciation, periods_posted. '
  'Transitions asset to fully_depreciated when NBV reaches residual_value.';

GRANT EXECUTE ON FUNCTION public.post_depreciation_period(uuid, uuid, uuid) TO service_role;

-- ── FUNCTION: post_asset_disposal ────────────────────────────────────────────
-- Records asset disposal and posts the disposal journal entry.
-- Returns the asset_disposals.id.
--
-- Journal entries:
--   Always: DR acc_depr_account (accumulated_depreciation)
--           CR asset_account    (acquisition_cost)
--   If proceeds > 0: DR 1930 Bank (proceeds)
--   If gain (proceeds > NBV):  CR gain_account (gain_loss)
--   If loss (proceeds < NBV):  DR loss_account (ABS(gain_loss))
--   Balance proof: DR = CR in all cases (verified above in header comment).

CREATE OR REPLACE FUNCTION public.post_asset_disposal(
  p_asset_id      uuid,
  p_period_id     uuid,
  p_disposal_type public.asset_disposal_type,
  p_disposal_date date,
  p_proceeds      numeric(14,2) DEFAULT 0,
  p_notes         text          DEFAULT NULL,
  p_actor_id      uuid          DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_asset       public.fixed_assets%ROWTYPE;
  v_class       public.fixed_asset_classes%ROWTYPE;
  v_gain_loss   numeric(14,2);
  v_lines       jsonb;
  v_entry_id    uuid;
  v_disposal_id uuid;
BEGIN
  SELECT * INTO v_asset FROM public.fixed_assets WHERE id = p_asset_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ASSET_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;
  IF v_asset.status = 'disposed' THEN
    RAISE EXCEPTION 'ASSET_ALREADY_DISPOSED: asset % is already disposed', p_asset_id
      USING ERRCODE = 'P0001';
  END IF;
  IF v_asset.status = 'draft' THEN
    RAISE EXCEPTION 'ASSET_DRAFT: cannot dispose a draft asset'
      USING ERRCODE = 'P0001';
  END IF;
  IF p_proceeds < 0 THEN
    RAISE EXCEPTION 'DISPOSAL_NEGATIVE_PROCEEDS: proceeds must be >= 0'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_class FROM public.fixed_asset_classes WHERE id = v_asset.asset_class_id;

  v_gain_loss := p_proceeds - v_asset.net_book_value;

  -- Build journal lines array
  v_lines := jsonb_build_array(
    -- Remove accumulated depreciation (debit contra-asset to zero it out)
    jsonb_build_object(
      'account_code',  v_class.accumulated_depr_account,
      'debit_amount',  v_asset.accumulated_depreciation,
      'credit_amount', 0,
      'description',   'Avyttring ackumulerade avskrivningar: ' || v_asset.asset_name
    ),
    -- Remove acquisition cost
    jsonb_build_object(
      'account_code',  v_class.asset_account,
      'debit_amount',  0,
      'credit_amount', v_asset.acquisition_cost,
      'description',   'Avyttring anskaffningsvärde: ' || v_asset.asset_name
    )
  );

  -- Book cash proceeds if any
  IF p_proceeds > 0 THEN
    v_lines := v_lines || jsonb_build_array(
      jsonb_build_object(
        'account_code',  '1930',
        'debit_amount',  p_proceeds,
        'credit_amount', 0,
        'description',   'Avyttring likvid: ' || v_asset.asset_name
      )
    );
  END IF;

  -- Book gain or loss
  IF v_gain_loss > 0 THEN
    v_lines := v_lines || jsonb_build_array(
      jsonb_build_object(
        'account_code',  v_class.disposal_gain_account,
        'debit_amount',  0,
        'credit_amount', v_gain_loss,
        'description',   'Realisationsvinst: ' || v_asset.asset_name
      )
    );
  ELSIF v_gain_loss < 0 THEN
    v_lines := v_lines || jsonb_build_array(
      jsonb_build_object(
        'account_code',  v_class.disposal_loss_account,
        'debit_amount',  ABS(v_gain_loss),
        'credit_amount', 0,
        'description',   'Realisationsförlust: ' || v_asset.asset_name
      )
    );
  END IF;

  v_entry_id := public.post_journal_entry(
    v_asset.organization_id,
    p_period_id,
    'standard'::public.journal_entry_type,
    p_disposal_date,
    'Avyttring anläggningstillgång: ' || v_asset.asset_name,
    v_lines,
    'FixedAsset.Disposed',
    'fixed_asset',
    p_asset_id,
    'D',
    NULL, NULL,
    p_actor_id
  );

  INSERT INTO public.asset_disposals
    (organization_id, asset_id, disposal_type, disposal_date,
     net_book_value_at_disposal, proceeds, gain_loss, journal_entry_id, notes, created_by)
  VALUES
    (v_asset.organization_id, p_asset_id, p_disposal_type, p_disposal_date,
     v_asset.net_book_value, p_proceeds, v_gain_loss, v_entry_id, p_notes, p_actor_id)
  RETURNING id INTO v_disposal_id;

  UPDATE public.fixed_assets
  SET status          = 'disposed',
      disposal_id     = v_disposal_id,
      net_book_value  = 0,
      updated_by      = p_actor_id,
      updated_at      = now()
  WHERE id = p_asset_id;

  RETURN v_disposal_id;
END;
$$;

COMMENT ON FUNCTION public.post_asset_disposal(uuid, uuid, public.asset_disposal_type, date, numeric, text, uuid) IS
  'Records fixed asset disposal and posts the disposal journal entry. '
  'Journal: DR acc_depr / (DR bank if proceeds) / (DR loss or CR gain) / CR asset_cost. '
  'Creates immutable asset_disposals record. Sets asset.status = ''disposed''.';

GRANT EXECUTE ON FUNCTION public.post_asset_disposal(uuid, uuid, public.asset_disposal_type, date, numeric, text, uuid) TO service_role;

-- ── FUNCTION: post_impairment_adjustment ─────────────────────────────────────
-- Posts an impairment write-down for an active or impaired asset.
-- Reduces net_book_value and regenerates the unposted depreciation schedule.
-- Journal: DR 7890 Nedskrivningar / CR accumulated_depr_account.

CREATE OR REPLACE FUNCTION public.post_impairment_adjustment(
  p_asset_id          uuid,
  p_period_id         uuid,
  p_impairment_date   date,
  p_impairment_amount numeric(14,2),
  p_reason            text DEFAULT NULL,
  p_actor_id          uuid DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_asset    public.fixed_assets%ROWTYPE;
  v_class    public.fixed_asset_classes%ROWTYPE;
  v_lines    jsonb;
  v_entry_id uuid;
BEGIN
  SELECT * INTO v_asset FROM public.fixed_assets WHERE id = p_asset_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ASSET_NOT_FOUND' USING ERRCODE = 'P0002';
  END IF;

  IF v_asset.status NOT IN ('active', 'impaired') THEN
    RAISE EXCEPTION
      'ASSET_NOT_IMPAIRMENT_ELIGIBLE: status is %, must be active or impaired',
      v_asset.status
      USING ERRCODE = 'P0001';
  END IF;

  IF p_impairment_amount <= 0 THEN
    RAISE EXCEPTION 'IMPAIRMENT_INVALID_AMOUNT: impairment amount must be positive'
      USING ERRCODE = 'P0001';
  END IF;

  IF p_impairment_amount > (v_asset.net_book_value - v_asset.residual_value) THEN
    RAISE EXCEPTION
      'IMPAIRMENT_EXCEEDS_DEPRECIABLE_NBV: amount (%) exceeds depreciable NBV (%)',
      p_impairment_amount, (v_asset.net_book_value - v_asset.residual_value)
      USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_class FROM public.fixed_asset_classes WHERE id = v_asset.asset_class_id;

  v_lines := jsonb_build_array(
    jsonb_build_object(
      'account_code',  '7890',
      'debit_amount',  p_impairment_amount,
      'credit_amount', 0,
      'description',
        'Nedskrivning: ' || v_asset.asset_name
        || COALESCE(' — ' || p_reason, '')
    ),
    jsonb_build_object(
      'account_code',  v_class.accumulated_depr_account,
      'debit_amount',  0,
      'credit_amount', p_impairment_amount,
      'description',   v_asset.asset_name || ' nedskrivning'
    )
  );

  v_entry_id := public.post_journal_entry(
    v_asset.organization_id,
    p_period_id,
    'standard'::public.journal_entry_type,
    p_impairment_date,
    'Nedskrivning anläggningstillgång: ' || v_asset.asset_name,
    v_lines,
    'FixedAsset.Impaired',
    'fixed_asset',
    p_asset_id,
    'D',
    NULL, NULL,
    p_actor_id
  );

  UPDATE public.fixed_assets
  SET accumulated_depreciation  = accumulated_depreciation + p_impairment_amount,
      net_book_value             = net_book_value - p_impairment_amount,
      status                     = 'impaired',
      updated_by                 = p_actor_id,
      updated_at                 = now()
  WHERE id = p_asset_id;

  -- Regenerate unposted schedule from new (lower) NBV
  PERFORM public.generate_depreciation_schedule(p_asset_id, p_actor_id);

  RETURN v_entry_id;
END;
$$;

COMMENT ON FUNCTION public.post_impairment_adjustment(uuid, uuid, date, numeric, text, uuid) IS
  'Posts an impairment write-down: DR 7890 Nedskrivningar / CR accumulated_depr_account. '
  'Updates asset.net_book_value and status → ''impaired''. '
  'Regenerates unposted depreciation schedule from the reduced NBV.';

GRANT EXECUTE ON FUNCTION public.post_impairment_adjustment(uuid, uuid, date, numeric, text, uuid) TO service_role;


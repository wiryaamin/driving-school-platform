-- Phase:     4G — Depreciation Engine & Asset Posting Functions
--
-- Implements deterministic depreciation accounting:
--   • depreciation_schedules — predetermined schedule per asset (immutable once posted)
--   • BAS 7890: Nedskrivningar anläggningstillgångar (Impairment write-downs)
--
--   SECURITY DEFINER functions:
--   register_fixed_asset(...)          — registers asset + posts acquisition journal
--   generate_depreciation_schedule(...)— builds full predetermined schedule
--   post_depreciation_period(...)      — posts one period via post_journal_entry()
--   post_asset_disposal(...)           — disposal accounting (gain/loss journal)
--   post_impairment_adjustment(...)    — impairment write-down + schedule regeneration
--
--   Views:
--   v_fixed_asset_register            — asset register with class + NBV details
--   v_depreciation_schedule_summary   — schedule progress per asset
--
-- Voucher series 'D' (Anläggningstillgångar) used for all Phase 4G journal entries.
--
-- Depreciation balance proof (straight-line):
--   Per period: DR 7820 (depr_exp) / CR 1259 (acc_depr) = amount
--   Over life:  SUM(amount) = acquisition_cost - residual_value ✓
--
-- Disposal balance proof (example: sale at gain):
--   DR acc_depr + DR proceeds → CR asset_cost + CR gain
--   acc_depr + proceeds = cost + (proceeds - NBV) = cost + proceeds - (cost - acc_depr)
--   = acc_depr + proceeds ✓
--
-- Dependencies:
--   20260605000001_phase4g_fixed_assets.sql
--   20260602000002_phase4d_posting_engine.sql — post_journal_entry()
-- ════════════════════════════════════════════════════════════════════════════


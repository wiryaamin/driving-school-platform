CREATE VIEW public.v_fixed_asset_register
WITH (security_invoker = true)
AS
SELECT
  fa.id,
  fa.organization_id,
  fa.asset_code,
  fa.asset_name,
  fa.description,
  fac.class_code,
  fac.class_name,
  fac.class_name_en,
  fa.depreciation_method,
  fa.acquisition_date,
  fa.acquisition_cost,
  fa.residual_value,
  (fa.acquisition_cost - fa.residual_value)   AS depreciable_amount,
  fa.useful_life_months,
  fa.accumulated_depreciation,
  fa.net_book_value,
  fa.periods_posted,
  (fa.useful_life_months - fa.periods_posted)  AS periods_remaining,
  fa.status,
  fa.last_depreciation_date,
  fa.fully_depreciated_at,
  fa.notes,
  fa.created_at,
  fa.updated_at,
  fac.asset_account,
  fac.accumulated_depr_account,
  fac.depreciation_exp_account
FROM  public.fixed_assets fa
JOIN  public.fixed_asset_classes fac ON fac.id = fa.asset_class_id;

COMMENT ON VIEW public.v_fixed_asset_register IS
  'Fixed asset register with class details and current net book values. '
  'security_invoker = true: each caller sees only their org''s assets.';

GRANT SELECT ON public.v_fixed_asset_register TO authenticated, service_role;

CREATE VIEW public.v_depreciation_schedule_summary
WITH (security_invoker = true)
AS
SELECT
  fa.id                                                        AS asset_id,
  fa.organization_id,
  fa.asset_code,
  fa.asset_name,
  fa.status                                                    AS asset_status,
  fa.acquisition_cost,
  fa.residual_value,
  COUNT(ds.id)                                                 AS total_periods,
  COUNT(ds.id) FILTER (WHERE ds.is_posted)                    AS posted_periods,
  COUNT(ds.id) FILTER (WHERE NOT ds.is_posted)                AS remaining_periods,
  MIN(ds.schedule_date) FILTER (WHERE NOT ds.is_posted)       AS next_depreciation_date,
  SUM(ds.depreciation_amount) FILTER (WHERE NOT ds.is_posted) AS remaining_depreciation,
  SUM(ds.depreciation_amount)                                  AS total_scheduled_depreciation
FROM  public.fixed_assets fa
LEFT  JOIN public.depreciation_schedules ds ON ds.asset_id = fa.id
GROUP BY fa.id, fa.organization_id, fa.asset_code, fa.asset_name,
         fa.status, fa.acquisition_cost, fa.residual_value;

COMMENT ON VIEW public.v_depreciation_schedule_summary IS
  'Depreciation schedule progress per asset. '
  'Shows posted vs remaining periods and next depreciation date. '
  'security_invoker = true.';

GRANT SELECT ON public.v_depreciation_schedule_summary TO authenticated, service_role;

-- ── depreciation_schedules ───────────────────────────────────────────────────
-- Predetermined depreciation schedule per asset. Generated by
-- generate_depreciation_schedule(). Each row = one monthly period.
-- Once is_posted = true the row is immutable (trigger below).

CREATE TABLE public.depreciation_schedules (
  id                  uuid          NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  organization_id     uuid          NOT NULL REFERENCES public.organizations(id)  ON DELETE RESTRICT,
  asset_id            uuid          NOT NULL REFERENCES public.fixed_assets(id)   ON DELETE RESTRICT,
  period_number       int           NOT NULL CHECK (period_number >= 1),
  schedule_date       date          NOT NULL,   -- first day of the target month
  depreciation_amount numeric(14,2) NOT NULL CHECK (depreciation_amount >= 0),
  opening_nbv         numeric(14,2) NOT NULL CHECK (opening_nbv >= 0),
  closing_nbv         numeric(14,2) NOT NULL CHECK (closing_nbv >= 0),
  is_posted           boolean       NOT NULL DEFAULT false,
  posted_at           timestamptz,
  journal_entry_id    uuid                   REFERENCES public.journal_entries(id) ON DELETE RESTRICT,
  created_at          timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT ds_asset_period_unique UNIQUE (asset_id, period_number),
  CONSTRAINT ds_nbv_balance         CHECK (ABS(closing_nbv - (opening_nbv - depreciation_amount)) < 0.02)
);

COMMENT ON TABLE public.depreciation_schedules IS
  'Predetermined depreciation schedule per asset. Generated by generate_depreciation_schedule(). '
  'Each row represents one monthly posting. Once is_posted=true, immutable (trigger). '
  'Ledger-derived: amounts are computed from acquisition_cost and residual_value. '
  'Unposted lines can be regenerated after an impairment write-down.';
COMMENT ON COLUMN public.depreciation_schedules.schedule_date IS
  'First day of the month this depreciation entry applies to.';
COMMENT ON COLUMN public.depreciation_schedules.period_number IS
  'Sequential number starting at 1 for the first depreciation month.';

CREATE OR REPLACE FUNCTION public.prevent_posted_depreciation_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF OLD.is_posted THEN
    RAISE EXCEPTION
      'DEPRECIATION_SCHEDULE_IMMUTABLE: posted depreciation schedule lines cannot be modified or deleted. '
      'Use post_impairment_adjustment() to correct asset value, then call generate_depreciation_schedule() '
      'to regenerate the unposted portion.'
      USING ERRCODE = 'P0001';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION public.prevent_posted_depreciation_mutation() IS
  'BEFORE UPDATE OR DELETE guard on depreciation_schedules. Blocks mutation of posted lines.';

CREATE TRIGGER depreciation_schedules_immutability
  BEFORE UPDATE OR DELETE ON public.depreciation_schedules
  FOR EACH ROW EXECUTE FUNCTION public.prevent_posted_depreciation_mutation();

ALTER TABLE public.depreciation_schedules ENABLE ROW LEVEL SECURITY;

CREATE POLICY "ds_org_read"

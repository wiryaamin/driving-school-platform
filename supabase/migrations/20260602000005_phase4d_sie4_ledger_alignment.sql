-- Platform:  Trafikskolan SaaS — Swedish Driving School ERP
-- Phase:     4D — SIE4 Ledger Alignment and Financial Reports
--
-- Makes the journal ledger the authoritative source for SIE4 exports and
-- financial reports. Implements Swedish accounting report views and the
-- ledger-based SIE4 generation function.
--
-- New table:
--   ledger_sie4_exports  — immutable SIE4 exports generated from the journal ledger
--
-- Views (security_invoker):
--   v_trial_balance     — account balances per period: opening/movements/closing
--   v_income_statement  — revenue and expense accounts (resultaträkning)
--   v_balance_sheet     — asset, liability, equity accounts (balansräkning)
--
-- Function:
--   generate_sie4_from_ledger(p_org_id, p_period_id, p_actor_id)
--     → Generates a complete SIE4 file from the journal ledger for a period.
--       Uses journal_entries + journal_lines as the authoritative source.
--       Includes: #FILTYP, #FORMAT, #GEN, #SIETYP, #FNAMN, #ORGNR, #MOMSNR,
--                 #KPTYP BAS2020, #RAR, #KONTO, #IB, #UB, #VER/#TRANS blocks.
--       SHA-256 hashes the content for integrity verification.
--       Idempotent: returns existing export_id if already generated for this period.
--
-- SIE4 invariants:
--   #VER line per journal entry (voucher_series + voucher_number + date)
--   #TRANS per journal line: positive = debit, negative = credit
--   #IB / #UB from account_balances (opening/closing per period)
--   #KONTO for every account referenced in the period's entries
--   #GEN = today's date (generation date)
--   #RAR 0 = fiscal year dates from the financial_period
--   SHA-256 hash stored in ledger_sie4_exports.content_hash
--
-- Dependencies:
--   20260602000001_phase4d_ledger_core.sql
--   20260602000002_phase4d_posting_engine.sql
--   20260601000001_phase4c_swedish_finance_foundation.sql — bas_account_catalog
--   20260601000003_phase4c_invoice_compliance.sql         — organization_swedish_settings
--   20260604000004_phase4c_sie4_exports.sql               — prevent_sie4_export_mutation()
-- ════════════════════════════════════════════════════════════════════════════

-- ── Section 1: ledger_sie4_exports ───────────────────────────────────────────
-- Immutable SIE4 exports generated from the journal ledger.
-- One export per organization per financial_period (unique constraint).
-- content_hash enables reproducibility verification.

CREATE TABLE public.ledger_sie4_exports (
  id               uuid          NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  organization_id  uuid          NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  financial_period_id uuid       NOT NULL REFERENCES public.financial_periods(id) ON DELETE RESTRICT,
  from_date        date          NOT NULL,
  to_date          date          NOT NULL,
  content_text     text          NOT NULL,
  content_hash     text          NOT NULL CHECK (length(content_hash) = 64),
  entry_count      int           NOT NULL DEFAULT 0 CHECK (entry_count >= 0),
  account_count    int           NOT NULL DEFAULT 0 CHECK (account_count >= 0),
  generated_at     timestamptz   NOT NULL DEFAULT now(),
  generated_by     uuid          REFERENCES auth.users(id) ON DELETE SET NULL,
  metadata         jsonb         NOT NULL DEFAULT '{}',

  CONSTRAINT lse_dates_check    CHECK (to_date >= from_date),
  CONSTRAINT lse_period_unique  UNIQUE (organization_id, financial_period_id)
);

COMMENT ON TABLE public.ledger_sie4_exports IS
  'Immutable SIE4 exports generated from the journal ledger. '
  'Each export covers one financial_period. SHA-256 hash enables reproducibility checks. '
  'Generated by generate_sie4_from_ledger(). Cannot be modified after creation.';

CREATE OR REPLACE FUNCTION public.prevent_ledger_sie4_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RAISE EXCEPTION 'LEDGER_SIE4_IMMUTABLE: ledger SIE4 exports are permanent records. '
    'Generate a new export to replace a previous one (requires period re-open).'
    USING ERRCODE = 'P0001';
END;
$$;

CREATE TRIGGER ledger_sie4_exports_immutability
  BEFORE UPDATE OR DELETE ON public.ledger_sie4_exports
  FOR EACH ROW EXECUTE FUNCTION public.prevent_ledger_sie4_mutation();

